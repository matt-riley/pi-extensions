import assert from "node:assert/strict";
import { test } from "node:test";
import { readFile } from "node:fs/promises";
import { lintComments, lintSuppressions } from "./comment-lint.mjs";

test("reports exact narration of an AST statement with source locations", () => {
  const findings = lintComments(
    "sample.ts",
    "// increment counter\ncounter++;\n// return result\nreturn result;\n",
  );
  assert.equal(findings.length, 2);
  assert.deepEqual(
    findings.map((x) => [x.rule, x.line]),
    [
      ["no-needless-comment", 1],
      ["no-needless-comment", 3],
    ],
  );
});

test("preserves documentation, rationale, directives and uncertain prose", () => {
  for (const source of [
    "/** Returns the cached result without another network request. */\nfunction result() { return cached; }",
    "/** return result */\nreturn result;",
    "// Increment counter because zero is reserved.\ncounter++;",
    "// return result only after validating it\nreturn result;",
    "// return result\n// Keep identity: callers compare references.\nreturn result;",
    "// eslint-disable-next-line no-plusplus\ncounter++;",
    "// Copyright Example\ncounter++;",
    'const url = "https://example.com//return result";',
    "const text = `\n// increment counter\ncounter++;\n`;",
    "const re = /\\/\\/ increment counter/;",
    "const a = <div>// increment counter</div>;",
    "previous(); // increment counter\ncounter++;",
    "// increment other\ncounter++;",
  ])
    assert.deepEqual(lintComments("sample.tsx", source), [], source);
});

test("handles prefix, postfix, call and ordinary block-comment narration", () => {
  for (const source of [
    "// increment the counter.\n++counter;",
    "// decrement counter\n--counter;",
    "// decrement the counter\ncounter--;",
    "/* call refresh */\nrefresh();",
  ])
    assert.equal(lintComments("sample.mjs", source).length, 1, source);
  for (const source of [
    "// increment counter\n+counter;",
    "// call refresh only when stale\nrefresh();",
    "// increment counter\ncache.counter++;",
    "// return result\nfunction result() { return cached; }",
  ])
    assert.deepEqual(lintComments("sample.ts", source), [], source);
});

test("does not pretend to parse Go documentation as JavaScript", () => {
  assert.deepEqual(
    lintComments(
      "sample.go",
      "// Result returns the cached result.\nfunc Result() int { return 1 }",
    ),
    [],
  );
});

test("a suppression without a reason is reported at the directive's line", () => {
  for (const [source, line] of [
    ["// eslint-disable-next-line no-console\nconsole.log(user);", 1],
    ["run();\n// @ts-ignore\nrun(input);", 2],
    ["// @ts-expect-error\nrun(input);", 1],
    ["// @ts-nocheck\nrun(input);", 1],
    ["/* oxlint-disable no-await-in-loop */\nrun();", 1],
    ["run(); // eslint-disable-line no-x -- short", 1],
    ["function f() { // oxlint-disable-line no-x\n}", 1],
    ["/* @ts-ignore */\nrun();", 1],
    ["const a = <div>{/* @ts-ignore */}</div>;", 1],
    ["// eslint-disable-next-line no-x\n// eslint-disable-next-line no-y\nrun();", 1],
  ]) {
    const findings = lintSuppressions("sample.tsx", source);
    assert.ok(findings.length >= 1, source);
    assert.deepEqual(
      [findings[0].rule, findings[0].line],
      ["suppression-needs-reason", line],
      source,
    );
    assert.match(findings[0].message, /Fix the finding, or state why the rule is wrong here\./);
  }
});

test("a suppression with an inline reason or a reason directly above it passes", () => {
  for (const source of [
    "// eslint-disable-next-line no-await-in-loop -- probes must run in order\nawait probe();",
    "/* oxlint-disable no-x -- generated file, regenerated by the build */\nrun();",
    "// @ts-expect-error: the library types omit the signal option\nrun(input);",
    "// @ts-ignore the vendored types predate this overload\nrun(input);",
    "// Sequential on purpose: the first hit wins.\n// eslint-disable-next-line no-await-in-loop\nawait probe();",
  ])
    assert.deepEqual(lintSuppressions("sample.ts", source), [], source);
});

test("only a directive in a comment counts, not a mention of one", () => {
  for (const source of [
    'const text = "// @ts-ignore";',
    "const text = `\n// eslint-disable-next-line no-x\n`;",
    "const re = /\\/\\/ @ts-ignore/;",
    "const a = <div>// @ts-ignore</div>;",
    "// Never add a bare @ts-ignore here.\nrun();",
    "/** A `@ts-expect-error` is a suppression. */\nfunction f() {}",
    "// eslint-disabled is not a directive\nrun();",
  ])
    assert.deepEqual(lintSuppressions("sample.tsx", source), [], source);
  assert.deepEqual(lintSuppressions("sample.py", "# @ts-ignore\nrun()"), []);
});

test("a reason above must be adjacent, on its own line, and not another directive", () => {
  for (const source of [
    "// Sequential on purpose: the first hit wins.\n\n// eslint-disable-next-line no-x\nrun();",
    "run(); // Sequential on purpose: the first hit wins.\n// eslint-disable-next-line no-x\nrun();",
    "// short\n// eslint-disable-next-line no-x\nrun();",
  ])
    assert.equal(lintSuppressions("sample.ts", source).length, 1, source);
});

test("the repository's existing suppressions keep their reasons", async () => {
  const source = await readFile(
    new URL("../packages/web-fetch/github.mjs", import.meta.url),
    "utf8",
  );
  assert.deepEqual(lintSuppressions("github.mjs", source), []);
  const stripped = source.replace(
    /^(?:[ \t]*\/\/(?! eslint-disable).*\n)+(?=[ \t]*\/\/ eslint-disable)/gm,
    "",
  );
  assert.equal(
    lintSuppressions("github.mjs", stripped).length,
    2,
    "both directives are found once their reasons are gone",
  );
});
